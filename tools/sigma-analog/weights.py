"""Sigma analog: data for black-and-white film directly from the Foveon layers (Merrill).

Generates `crates/develop/src/analog/data.rs` (constants) and prints a check table.

Sources and licences:
- Spectral sensitivity Sigma SD1 Merrill (whole camera, 400–680 nm, 10 nm), measured at the National Physical
  Laboratory: Darrodi, Finlayson, Goodman, Mackiewicz, "Reference data set for camera spectral sensitivity
  estimation", JOSA A 32(3):381, 2015. Numbers from colour-science (BSD-3-Clause), name "Sigma SDMerill (NPL)".
- Training spectra: 190 reflectance spectra from rawtoaces (Academy of Motion Picture Arts and Sciences,
  via colour-science) and ColorChecker "N Ohta" (colour-science). Only sums computed from them are built in
  (3×29 and 3×3), no spectra.
- Standard illuminant D55 (CIE, public domain).
- Noise covariance of the layers per ISO: own measurement on DP2 Merrill shots (flat blocks, see
  `noise.py`), file `noise.jsonl` as input.

Usage: python -I weights.py noise.jsonl OUTPUT.rs
"""
import json, sys
from collections import defaultdict
import numpy as np
import colour

shape = colour.SpectralShape(400, 680, 10)
WL = np.arange(400, 690, 10.0)
SSF = np.asarray(colour.MSDS_CAMERA_SENSITIVITIES["Sigma SDMerill (NPL)"].copy().align(shape).values)  # R,G,B = bottom, middle, top
D55 = np.asarray(colour.SDS_ILLUMINANTS["D55"].copy().align(shape).values)
CMF = np.asarray(colour.MSDS_CMFS["CIE 1931 2 Degree Standard Observer"].copy().align(shape).values)

def training():
    td = colour.characterisation.read_training_data_rawtoaces_v1()
    nat = np.clip(np.asarray(td.copy().align(shape).values).T, 0, 1)
    cc = colour.SDS_COLOURCHECKERS["ColorChecker N Ohta"]
    ccs = np.array([np.asarray(v.copy().align(shape).values) for v in cc.values()])
    return np.vstack([nat, ccs])

def moments(R):
    """K (3×29), A (3×3), n: sums over the training spectra with weight 1/Y² (relative error)."""
    white = D55 @ SSF
    L = (R * D55) @ SSF / white                  # normalised layer values, white = 1
    Y = (R * D55) @ CMF[:, 1] / (D55 @ CMF[:, 1])
    om = 1 / np.maximum(Y, 0.01) ** 2
    K = np.einsum('i,ik,il->kl', om, L, R * D55)   # b = K g / (D55·g)
    A = np.einsum('i,ik,il->kl', om, L, L)
    return K, A, om.sum(), L, om

def interp_profile(stock, profdir):
    d = json.load(open(f"{profdir}/{stock}.json"))["data"]
    wl = np.array(d["wavelengths"]); ls = np.array([np.nan if r[0] is None else r[0] for r in d["log_sensitivity"]], float)
    s = np.where(np.isfinite(ls), 10 ** np.nan_to_num(ls, nan=-10), 0.0)
    return np.interp(WL, wl, s, left=0, right=0)

def solve(K, A, n, g, C, beta=0.0):
    b = K @ g / (D55 @ g)
    H = A / n + beta * C
    c = b / n
    Hi = np.linalg.inv(H); one = np.ones(3)
    nu = (1 - one @ Hi @ c) / (one @ Hi @ one)
    return Hi @ (c + nu * one)

def noise_table(path):
    by = defaultdict(list)
    for l in open(path):
        d = json.loads(l)
        by[int(d['iso'])].append(np.array(d['cov']))
    return {iso: np.median(np.array(v), axis=0) for iso, v in sorted(by.items())}

def rust(K, A, n, noise):
    f = lambda v: ", ".join(f"{x:.6e}" for x in v)
    out = ["// Generated by tools/sigma-analog/weights.py – do not edit by hand.",
           "// Sources and licences: see there and THIRD_PARTY.md (NPL measurement Darrodi et al. 2015 via colour-science,",
           "// BSD-3-Clause; training sums from rawtoaces/ColorChecker; noise own measurement).", "",
           "/// Wavelengths 400, 410 … 680 nm", "pub const N: usize = 29;",
           "/// Spectral sensitivity Sigma SD1 Merrill per layer [bottom, middle, top] (NPL, relative)", "#[allow(dead_code)]",
           "pub const SSF: [[f64; 3]; N] = [" + ", ".join(f"[{f(r)}]" for r in SSF) + "];",
           "/// Standard illuminant D55 (CIE, relative)", f"pub const D55: [f64; N] = [{f(D55)}];",
           "/// Training sum K[layer][λ] = Σ ω·L·R(λ)·D55(λ)", "pub const K: [[f64; N]; 3] = [" + ", ".join(f"[{f(r)}]" for r in K) + "];",
           "/// Training sum A = Σ ω·L·Lᵀ and Σ ω", "pub const A: [[f64; 3]; 3] = [" + ", ".join(f"[{f(r)}]" for r in A) + "];",
           f"pub const N_OMEGA: f64 = {n:.6e};",
           "/// Relative noise covariance of the normalised layers at mid-grey (scene 0.184) per ISO, DP2 Merrill, after",
           "/// the base development (noise reduction standard), full resolution: (ISO, covariance [bottom, middle, top])",
           "pub const NOISE: [(f64, [[f64; 3]; 3]); %d] = [" % len(noise) + ", ".join(f"({iso}.0, [" + ", ".join(f"[{f(r)}]" for r in c) + "])" for iso, c in noise.items()) + "];", ""]
    return "\n".join(out)

if __name__ == "__main__":
    noise = noise_table(sys.argv[1])
    profdir = sys.argv[3] if len(sys.argv) > 3 else "third_party/spektrafilm-rs/data/profiles"
    R = training()
    K, A, n, L, om = moments(R)
    open(sys.argv[2], "w").write(rust(K, A, n, noise))
    for stock in ["kodak_trix_400", "ilford_hp5_plus", "kodak_tmax_100", "ilford_delta_100", "ilford_fp4_plus", "fujifilm_acros_100_ii", "agfa_apx_100", "kodak_doublex", "ilford_ortho_plus"]:
        g = interp_profile(stock, profdir)
        for iso, C in noise.items():
            w = solve(K, A, n, g, C)
            E = (R * D55) @ g / (D55 @ g); est = L @ w
            err = np.sqrt(np.sum(om * (est - E) ** 2) / n)
            print(f"{stock:24s} ISO {iso:5d} w = {np.round(w,3)} error {err:.4f} noise {np.sqrt(w@C@w):.4f}")
